	// ---- the 65536-entry sin lookup table ---------------------------------
	// The table is the single most load-bearing constant in Mth: every sin()/cos()
	// call in the game indexes it. Rather than ship 65536 golden rows we emit
	//   * an FNV-1a 64 hash over the raw bits of the WHOLE table, and
	//   * a deterministic sample (first 512, last 512, every 137th).
	// Matching the hash means all 65536 entries are bit-identical.
	private static void sinTable(final Out o) {
		final float[] table = new float[65536];
		for (int i = 0; i < table.length; i++) {
			table[i] = (float) Math.sin(i / 10430.378350470453);
		}

		long h = 0xCBF29CE484222325L;
		for (int i = 0; i < table.length; i++) {
			int bits = Float.floatToRawIntBits(table[i]);
			for (int b = 0; b < 4; b++) {
				h ^= (bits >>> (8 * b)) & 0xFFL;
				h *= 0x100000001B3L;
			}
		}

		o.fn("sinTableHash", "", "i64");
		o.row("", Out.i64(h));
		o.blank();

		List<Integer> idx = new ArrayList<>();
		for (int i = 0; i < 512; i++) {
			idx.add(i);
		}

		for (int i = 65536 - 512; i < 65536; i++) {
			idx.add(i);
		}

		for (int i = 0; i < 65536; i += 137) {
			idx.add(i);
		}

		o.fn("sinTable", "i32", "f32");
		for (int i : idx) {
			o.row(Out.i32(i), Out.f32(table[i]));
		}

		o.blank();
	}

	/**
	 * Dumps the FULL sin / asin / cos lookup tables so the Rust side can embed them
	 * verbatim instead of calling the host libm.
	 *
	 * Why embed: Java's Math.sin is permitted a 1-ulp error and the exact value
	 * depends on JVM internals (fdlibm vs. x86 intrinsic). Rust's f64::sin links
	 * the platform libm. Across 65536 entries a 1-ulp double difference can still
	 * flip the rounded f32 result for a handful of indices -- and one flipped
	 * entry changes every sin()/cos() call that lands on it, i.e. block rotation,
	 * entity yaw, camera angles. Embedding removes the host-libm dependency and
	 * makes the table identical on every platform and CPU.
	 * See _porting/DESIGN_DECISIONS.md (#embedded-trig-tables).
	 *
	 * This file is an INPUT for _porting/tools/gen_tables.py, not for the tests.
	 */
	public static void emitTables(final Path path) throws Exception {
		Out o = new Out();
		o.comment("Full lookup tables from net.minecraft.util.Mth (Minecraft 26.2).");
		o.comment("INPUT for _porting/tools/gen_tables.py -- NOT read by the parity tests.");
		o.blank();

		o.fn("SIN", "i32", "f32");
		for (int i = 0; i < 65536; i++) {
			o.row(Out.i32(i), Out.f32((float) Math.sin(i / 10430.378350470453)));
		}
		o.blank();

		double[] asin = new double[257];
		double[] cos = new double[257];
		for (int ind = 0; ind < 257; ind++) {
			double v = ind / 256.0;
			double asinv = Math.asin(v);
			cos[ind] = Math.cos(asinv);
			asin[ind] = asinv;
		}

		o.fn("ASIN_TAB", "i32", "f64");
		for (int i = 0; i < 257; i++) {
			o.row(Out.i32(i), Out.f64(asin[i]));
		}
		o.blank();

		o.fn("COS_TAB", "i32", "f64");
		for (int i = 0; i < 257; i++) {
			o.row(Out.i32(i), Out.f64(cos[i]));
		}
		o.blank();

		o.write(path);
	}
