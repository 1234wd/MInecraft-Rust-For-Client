	// ---- String / predicate / Fraction taking methods ---------------------
	private static void strings(final Out o) {
		o.fn("getInt", "str i32", "i32");
		for (String s : new String[]{"0", "1", "-1", "42", "2147483647", "-2147483648", "2147483648",
				"", " ", "+7", "007", "1.0", "abc", "0x10", "99999999999999999999"}) {
			o.row(Out.join(Out.str(s), Out.i32(5)), Out.i32(Mth.getInt(s, 5)));
		}
		o.blank();

		o.fn("mulAndTruncate", "f64 i32", "i32");
		for (double d : new double[]{0.0, 0.5, -0.5, 1.0, -1.0, 0.25, 0.75, 1.0 / 3.0, 2.0 / 3.0, -2.0 / 3.0, 10.0, -10.0, 100.0}) {
			for (int f : new int[]{1, -1, 2, 3, 7, 100, -100}) {
				o.row(Out.join(Out.f64(d), Out.i32(f)), Out.i32(Mth.mulAndTruncate(Fraction.getFraction(d), f)));
			}
		}
		o.blank();

		o.fn("binarySearch", "i32 i32", "i32");
		for (int[] range : new int[][]{{0, 0}, {0, 1}, {0, 8}, {-8, 8}, {-100, 100}, {5, 5}, {0, 2147483647}}) {
			IntPredicate cond = i -> i % 3 == 0;
			o.row(Out.join(Out.i32(range[0]), Out.i32(range[1])), Out.i32(Mth.binarySearch(range[0], range[1], cond)));
		}
		o.blank();
	}

