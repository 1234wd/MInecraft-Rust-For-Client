package p;

import java.io.OutputStreamWriter;
import java.io.PrintWriter;
import java.lang.reflect.Constructor;
import java.nio.charset.StandardCharsets;
import java.nio.file.FileSystemException;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Session 22 small-file oracle. Writes {@code _porting/test-data/small_probe.txt}.
 *
 * <p>Everything here runs against Mojang's bytecode (minecraft-merged-deobf-26.2.jar) on JDK 25.
 * Like {@code NbtProbe} it is NOT part of run.ps1's oracle; build and run it by hand from
 * {@code _porting/java-oracle}:
 *
 * <pre>
 *   javac -d %TEMP%\smallprobe -cp "&lt;mc jar&gt;;lib\*" src\p\SmallProbe.java
 *   java -cp "%TEMP%\smallprobe;&lt;mc jar&gt;;lib\*" p.SmallProbe ..\test-data\small_probe.txt
 * </pre>
 *
 * <p>Line format: TAB-separated fields, first field = group. Strings go through {@link #esc}
 * (backslash doubled, chars outside 0x20..0x7E as {@code \\uXXXX} UTF-16 code units, null as
 * {@code \\N}) -- the same convention as {@code nbt_probe.txt}. Floats and doubles are written as
 * the hex of their RAW bits, never as decimals.
 *
 * <p>The Rust twin is {@code _porting/tests/session22.rs}. Every case below is built there with
 * the same arguments, and {@code every_probe_group_is_claimed} fails if a group written here is
 * not read by a test. The output must be byte-for-byte reproducible: nothing here may print an
 * identity hash code, a clock, or anything else that differs between runs.
 */
public class SmallProbe {
	static PrintWriter out;
	static int rows;

	static void row(String... fields) {
		out.print(String.join("\t", fields));
		out.print("\n");
		rows++;
	}

	static String esc(String s) {
		if (s == null) {
			return "\\N";
		}
		StringBuilder b = new StringBuilder();
		for (int i = 0; i < s.length(); i++) {
			char c = s.charAt(i);
			if (c == '\\') {
				b.append("\\\\");
			} else if (c >= 0x20 && c <= 0x7e) {
				b.append(c);
			} else {
				b.append(String.format("\\u%04x", (int) c));
			}
		}
		return b.toString();
	}

	static String f(float v) {
		return Integer.toHexString(Float.floatToRawIntBits(v));
	}

	static String d(double v) {
		return Long.toHexString(Double.doubleToRawLongBits(v));
	}

	static String b(boolean v) {
		return String.valueOf(v);
	}

	static String i(int v) {
		return String.valueOf(v);
	}

	static String l(long v) {
		return String.valueOf(v);
	}

	public static void main(String[] args) throws Exception {
		Path target = Path.of(args[0]);
		try (PrintWriter w = new PrintWriter(new OutputStreamWriter(Files.newOutputStream(target), StandardCharsets.UTF_8))) {
			out = w;
			out.print("# small_probe.txt -- GENERATED by _porting/java-oracle/src/p/SmallProbe.java against "
				+ "minecraft-merged-deobf-26.2.jar on JDK " + System.getProperty("java.version")
				+ ". TAB-separated; see SmallProbe's javadoc for the format.\n");
			exceptions();
		}
		System.err.println("small_probe: " + rows + " rows -> " + target);
	}

	// ------------------------------------------------------------------ EXC / EXCFS: exception classes

	/** Message pool: plain, empty, null, a control character, and non-ASCII (BMP + a surrogate pair). */
	static final String[] MSGS = {"boom", "", null, "tab\there", "é中😀"};

	/**
	 * {@code EXC  id  msgIndex  causeIndex  className  superclass  isRuntime  getMessage  toString  causeToString}.
	 * {@code causeIndex} is -1 for a constructor with no cause parameter.
	 */
	static void exc(String id, int msg, int cause, Throwable t) {
		Throwable c = t.getCause();
		row("EXC", id, i(msg), i(cause), t.getClass().getName(), t.getClass().getSuperclass().getName(),
			b(t instanceof RuntimeException), esc(t.getMessage()), esc(t.toString()), esc(c == null ? null : c.toString()));
	}

	/** {@code EXCFS  id  msgIndex  getFile  getOtherFile  getReason} for the java.nio.file family. */
	static void excFs(String id, int msg, FileSystemException t) {
		row("EXCFS", id, i(msg), esc(t.getFile()), esc(t.getOtherFile()), esc(t.getReason()));
	}

	/** Cause pool. The Rust side rebuilds each from its {@code toString}, which is all a cause contributes. */
	static Throwable cause(int k) {
		return switch (k) {
			case 0 -> new RuntimeException("inner");
			case 1 -> new java.io.IOException();
			case 2 -> new IllegalStateException("");
			default -> null;
		};
	}

	static final int CAUSES = 4;

	static void exceptions() throws Exception {
		for (int m = 0; m < MSGS.length; m++) {
			String s = MSGS[m];
			exc("GpuDeviceLossException", m, -1, new com.mojang.blaze3d.GpuDeviceLossException(s));
			exc("GpuOutOfMemoryException", m, -1, new com.mojang.blaze3d.GpuOutOfMemoryException(s));
			exc("ShaderCompileException", m, -1, new com.mojang.blaze3d.vulkan.glsl.ShaderCompileException(s));
			exc("EncodeJsonRpcException", m, -1, new net.minecraft.server.jsonrpc.methods.EncodeJsonRpcException(s));
			exc("InvalidParameterJsonRpcException", m, -1, new net.minecraft.server.jsonrpc.methods.InvalidParameterJsonRpcException(s));
			exc("InvalidRequestJsonRpcException", m, -1, new net.minecraft.server.jsonrpc.methods.InvalidRequestJsonRpcException(s));
			exc("MethodNotFoundJsonRpcException", m, -1, new net.minecraft.server.jsonrpc.methods.MethodNotFoundJsonRpcException(s));
			exc("CowFSIllegalArgumentException", m, -1,
				new net.minecraft.util.filefix.virtualfilesystem.exception.CowFSIllegalArgumentException(s));
			exc("SilentInitException", m, -1, new net.minecraft.client.main.SilentInitException(s));
			exc("SurfaceException", m, -1, new com.mojang.blaze3d.systems.SurfaceException(s));

			FileSystemException[] fs = {
				new net.minecraft.util.filefix.virtualfilesystem.exception.CowFSFileSystemException(s),
				new net.minecraft.util.filefix.virtualfilesystem.exception.CowFSDirectoryNotEmptyException(s),
				new net.minecraft.util.filefix.virtualfilesystem.exception.CowFSFileAlreadyExistsException(s),
				new net.minecraft.util.filefix.virtualfilesystem.exception.CowFSNoSuchFileException(s),
				new net.minecraft.util.filefix.virtualfilesystem.exception.CowFSNotDirectoryException(s),
			};
			for (FileSystemException e : fs) {
				String id = e.getClass().getSimpleName();
				exc(id, m, -1, e);
				excFs(id, m, e);
			}

			for (int c = 0; c < CAUSES; c++) {
				exc("SilentInitException", m, c, new net.minecraft.client.main.SilentInitException(s, cause(c)));
				Throwable cc = cause(c);
				exc("RealmsHttpException", m, c,
					new com.mojang.realmsclient.exception.RealmsHttpException(s, cc instanceof Exception e ? e : null));
			}
		}
		for (int c = 0; c < CAUSES; c++) {
			exc("CryptException", -1, c, new net.minecraft.util.CryptException(cause(c)));
			exc("SurfaceException", -1, c, new com.mojang.blaze3d.systems.SurfaceException(cause(c)));
		}

		// The singleton. Its private constructor never sets a message, and it clears its own stack trace.
		net.minecraft.server.RunningOnDifferentThreadException r =
			net.minecraft.server.RunningOnDifferentThreadException.RUNNING_ON_DIFFERENT_THREAD;
		exc("RunningOnDifferentThreadException", -1, -1, r);
		row("EXCSTACK", "RunningOnDifferentThreadException", i(r.getStackTrace().length), i(r.fillInStackTrace().getStackTrace().length),
			b(r.fillInStackTrace() == r));

		// BackendCreationException: message + Reason + an immutable copy of the capability list.
		for (com.mojang.blaze3d.systems.BackendCreationException.Reason reason
			: com.mojang.blaze3d.systems.BackendCreationException.Reason.values()) {
			row("BCREASON", reason.name(), i(reason.ordinal()), esc(reason.displayName()));
		}
		java.util.List<String> caps = new java.util.ArrayList<>(java.util.List.of("a", "b"));
		com.mojang.blaze3d.systems.BackendCreationException bce = new com.mojang.blaze3d.systems.BackendCreationException(
			MSGS[0], com.mojang.blaze3d.systems.BackendCreationException.Reason.VULKAN_NO_DEVICE, caps);
		caps.add("c");
		exc("BackendCreationException", 0, -1, bce);
		boolean immutable;
		try {
			bce.getMissingCapabilities().add("x");
			immutable = false;
		} catch (UnsupportedOperationException e) {
			immutable = true;
		}
		row("BCE", "three-arg", bce.getReason().name(), String.join(",", bce.getMissingCapabilities()), b(immutable));
		com.mojang.blaze3d.systems.BackendCreationException two = new com.mojang.blaze3d.systems.BackendCreationException(
			MSGS[2], com.mojang.blaze3d.systems.BackendCreationException.Reason.OTHER);
		exc("BackendCreationException", 2, -1, two);
		row("BCE", "two-arg", two.getReason().name(), String.join(",", two.getMissingCapabilities()),
			b(two.getMissingCapabilities().isEmpty()));
		String npe;
		try {
			new com.mojang.blaze3d.systems.BackendCreationException("m",
				com.mojang.blaze3d.systems.BackendCreationException.Reason.OTHER, java.util.Arrays.asList("a", null));
			npe = "none";
		} catch (NullPointerException e) {
			npe = e.getClass().getName();
		}
		row("BCE", "null-element", npe, "", "");
	}
}
