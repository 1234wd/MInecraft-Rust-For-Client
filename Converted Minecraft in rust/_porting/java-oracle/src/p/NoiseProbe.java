package p;

import it.unimi.dsi.fastutil.doubles.DoubleArrayList;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.stream.IntStream;
import net.minecraft.util.RandomSource;
import net.minecraft.world.level.levelgen.LegacyRandomSource;
import net.minecraft.world.level.levelgen.WorldgenRandom;
import net.minecraft.world.level.levelgen.XoroshiroRandomSource;
import net.minecraft.world.level.levelgen.synth.ImprovedNoise;
import net.minecraft.world.level.levelgen.synth.NormalNoise;
import net.minecraft.world.level.levelgen.synth.PerlinNoise;
import net.minecraft.world.level.levelgen.synth.PerlinSimplexNoise;
import net.minecraft.world.level.levelgen.synth.SimplexNoise;

/**
 * Session 19 probe for the worldgen noise port (levelgen/synth). Run against the real 26.2 jar
 * (JDK 25), output committed as _porting/test-data/noise_probe.txt.
 *
 * Line format (one fact per line, '|' separated, doubles as raw 64-bit hex bits):
 *   <kind>|<case id>|<arg>|<arg>|...|<result>
 * Every random source is described by its case id; the Rust test rebuilds the same source.
 *   L<seed>  = new LegacyRandomSource(seed)
 *   X<seed>  = new XoroshiroRandomSource(seed)
 *   W<seed>  = new WorldgenRandom(new LegacyRandomSource(seed))
 */
public class NoiseProbe {
    static PrintStream out;

    static String h(double d) {
        return String.format("%016x", Double.doubleToRawLongBits(d));
    }

    static RandomSource src(String id) {
        long seed = Long.parseLong(id.substring(1));
        return switch (id.charAt(0)) {
            case 'L' -> new LegacyRandomSource(seed);
            case 'X' -> new XoroshiroRandomSource(seed);
            case 'W' -> new WorldgenRandom(new LegacyRandomSource(seed));
            default -> throw new IllegalArgumentException(id);
        };
    }

    static final double[] COORDS = {
        0.0, 0.5, 1.0, -1.0, -0.5, 3.75, -3.75, 17.123456789, -17.123456789, 255.999, 256.0,
        1000.25, -1000.25, 33554432.0, -33554431.5, 1.0E7 + 0.3, 1.0E-9, -1.0E-9, 123456.789
    };

    public static void main(String[] args) throws Exception {
        out = new PrintStream(new java.io.FileOutputStream(args[0]), true, StandardCharsets.UTF_8);
        out.println("# noise probe -- GENERATED by _porting/java-oracle/src/p/NoiseProbe.java against minecraft-merged-deobf-26.2.jar");
        out.println("# kind|case|args...|result ; doubles are raw IEEE-754 bits in hex");
        String[] seeds = {"L0", "L1", "L-1", "L12345", "L-987654321", "L25214903917", "X0", "X42", "X-7"};

        // ---- SimplexNoise
        for (String s : seeds) {
            SimplexNoise n = new SimplexNoise(src(s));
            out.println("simplex.origin|" + s + "|" + h(n.xo) + "|" + h(n.yo) + "|" + h(n.zo));
            for (int a = 0; a < COORDS.length; a++) {
                for (int b = 0; b < COORDS.length; b += 3) {
                    double x = COORDS[a], y = COORDS[b];
                    out.println("simplex.2d|" + s + "|" + h(x) + "|" + h(y) + "|" + h(n.getValue(x, y)));
                    double z = COORDS[(a + b) % COORDS.length];
                    out.println("simplex.3d|" + s + "|" + h(x) + "|" + h(y) + "|" + h(z) + "|" + h(n.getValue(x, y, z)));
                }
            }
        }

        // ---- ImprovedNoise
        for (String s : seeds) {
            ImprovedNoise n = new ImprovedNoise(src(s));
            out.println("improved.origin|" + s + "|" + h(n.xo) + "|" + h(n.yo) + "|" + h(n.zo));
            StringBuilder sb = new StringBuilder();
            n.parityConfigString(sb);
            out.println("improved.parity|" + s + "|" + sb.toString().replace(' ', '_'));
            for (int a = 0; a < COORDS.length; a++) {
                for (int b = 0; b < COORDS.length; b += 4) {
                    double x = COORDS[a], y = COORDS[b], z = COORDS[(a * 7 + b) % COORDS.length];
                    out.println("improved.noise|" + s + "|" + h(x) + "|" + h(y) + "|" + h(z) + "|" + h(n.noise(x, y, z)));
                    double yScale = (b % 2 == 0) ? 0.5 : 0.0, yFudge = (a % 3 == 0) ? 0.25 : -1.0;
                    out.println("improved.fudge|" + s + "|" + h(x) + "|" + h(y) + "|" + h(z) + "|" + h(yScale) + "|" + h(yFudge) + "|"
                        + h(n.noise(x, y, z, yScale, yFudge)));
                    double[] d = {0.5, -0.25, 1.0};
                    double v = n.noiseWithDerivative(x, y, z, d);
                    out.println("improved.deriv|" + s + "|" + h(x) + "|" + h(y) + "|" + h(z) + "|" + h(v) + "|" + h(d[0]) + "|" + h(d[1]) + "|" + h(d[2]));
                }
            }
        }

        // ---- PerlinNoise.wrap
        for (double x : COORDS) {
            out.println("perlin.wrap|-|" + h(x) + "|" + h(PerlinNoise.wrap(x)));
            out.println("perlin.wrap|-|" + h(x * 1.0E3) + "|" + h(PerlinNoise.wrap(x * 1.0E3)));
        }

        // ---- PerlinNoise (new init via create(random, firstOctave, amplitudes))
        Object[][] perlinCases = {
            {"X0", -3, new double[]{1.0, 1.0, 0.0, 1.0}},
            {"X42", -7, new double[]{1.0, 2.0, 1.0, 0.0, 0.0, 0.5}},
            {"X-7", 0, new double[]{1.0}},
            {"L12345", -4, new double[]{0.0, 1.0, 1.0}},
        };
        for (Object[] c : perlinCases) {
            String s = (String) c[0];
            int first = (Integer) c[1];
            double[] amps = (double[]) c[2];
            PerlinNoise n = PerlinNoise.create(src(s), first, new DoubleArrayList(amps));
            emitPerlin("perlin.new|" + s + ";" + first + ";" + ampStr(amps), n);
        }
        // ---- PerlinNoise.create(random, List<Integer>) (sorted set of octaves)
        PerlinNoise fromSet = PerlinNoise.create(src("X99"), List.of(-5, -3, -1, 0, -3));
        emitPerlin("perlin.set|X99;-5,-3,-1,0", fromSet);
        // ---- legacy init (BlendedNoise and the old nether biome noise)
        PerlinNoise legacyBlended = PerlinNoise.createLegacyForBlendedNoise(src("L777"), IntStream.rangeClosed(-15, 0));
        emitPerlin("perlin.legacyBlended|L777;-15..0", legacyBlended);
        PerlinNoise legacyNether = PerlinNoise.createLegacyForLegacyNetherBiome(src("L31337"), -7, new DoubleArrayList(new double[]{1.0, 1.0, 0.0, 1.0}));
        emitPerlin("perlin.legacyNether|L31337;-7;1,1,0,1", legacyNether);
        try {
            PerlinNoise.createLegacyForLegacyNetherBiome(src("L1"), 0, new DoubleArrayList(new double[]{1.0, 1.0}));
            out.println("perlin.error|positive|none");
        } catch (Exception e) {
            out.println("perlin.error|positive|" + e.getClass().getName() + ": " + e.getMessage());
        }
        try {
            PerlinNoise.create(src("X1"), List.of());
            out.println("perlin.error|empty|none");
        } catch (Exception e) {
            out.println("perlin.error|empty|" + e.getClass().getName() + ": " + e.getMessage());
        }

        // ---- PerlinSimplexNoise
        Object[][] psCases = {
            {"W0", List.of(-3, -2, -1, 0)},
            {"W42", List.of(-6, -4, 0)},
            {"W1234", List.of(0, 1, 2)},
            {"W-5", List.of(-2, 0, 3)},
            {"L8", List.of(-1)},
        };
        for (Object[] c : psCases) {
            String s = (String) c[0];
            @SuppressWarnings("unchecked") List<Integer> oct = (List<Integer>) c[1];
            PerlinSimplexNoise n = new PerlinSimplexNoise(src(s), oct);
            String id = s + ";" + oct.toString().replace(" ", "");
            for (int a = 0; a < COORDS.length; a++) {
                for (int b = 0; b < COORDS.length; b += 5) {
                    double x = COORDS[a], y = COORDS[b];
                    out.println("perlinSimplex.value|" + id + "|" + h(x) + "|" + h(y) + "|true|" + h(n.getValue(x, y, true)));
                    out.println("perlinSimplex.value|" + id + "|" + h(x) + "|" + h(y) + "|false|" + h(n.getValue(x, y, false)));
                }
            }
        }

        // ---- NormalNoise
        Object[][] nnCases = {
            {"X0", -3, new double[]{1.0, 1.0, 0.0, 1.0}},
            {"X1234", -9, new double[]{1.0, 1.0, 2.0, 2.0, 2.0, 1.0, 1.0, 1.0, 1.0}},
            {"X-1", -1, new double[]{0.0, 0.0}},
        };
        for (Object[] c : nnCases) {
            String s = (String) c[0];
            int first = (Integer) c[1];
            double[] amps = (double[]) c[2];
            NormalNoise n = NormalNoise.create(src(s), first, amps);
            emitNormal("normal.new|" + s + ";" + first + ";" + ampStr(amps), n);
        }
        NormalNoise legacy = NormalNoise.createLegacyNetherBiome(src("L4242"), new NormalNoise.NoiseParameters(-7, 1.0, 1.0));
        emitNormal("normal.legacy|L4242;-7;1,1", legacy);
        out.close();
    }

    static String ampStr(double[] amps) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < amps.length; i++) {
            if (i > 0) sb.append(',');
            sb.append(amps[i]);
        }
        return sb.toString();
    }

    static void emitPerlin(String id, PerlinNoise n) {
        StringBuilder sb = new StringBuilder();
        n.parityConfigString(sb);
        out.println(id + "|parity|" + sb.toString().replace(' ', '_'));
        out.println(id + "|maxBroken|" + h(0.0) + "|" + h(n.maxBrokenValue(0.0)));
        out.println(id + "|maxBroken|" + h(1.5) + "|" + h(n.maxBrokenValue(1.5)));
        for (int a = 0; a < COORDS.length; a++) {
            for (int b = 0; b < COORDS.length; b += 4) {
                double x = COORDS[a], y = COORDS[b], z = COORDS[(a * 5 + b) % COORDS.length];
                out.println(id + "|value|" + h(x) + "|" + h(y) + "|" + h(z) + "|" + h(n.getValue(x, y, z)));
                out.println(id + "|valueFudge|" + h(x) + "|" + h(y) + "|" + h(z) + "|" + h(0.125) + "|" + h(0.0625) + "|"
                    + h(n.getValue(x, y, z, 0.125, 0.0625)));
            }
        }
    }

    static void emitNormal(String id, NormalNoise n) {
        StringBuilder sb = new StringBuilder();
        n.parityConfigString(sb);
        out.println(id + "|parity|" + sb.toString().replace(' ', '_'));
        out.println(id + "|max|" + h(n.maxValue()));
        for (int a = 0; a < COORDS.length; a++) {
            for (int b = 0; b < COORDS.length; b += 4) {
                double x = COORDS[a], y = COORDS[b], z = COORDS[(a * 3 + b) % COORDS.length];
                out.println(id + "|value|" + h(x) + "|" + h(y) + "|" + h(z) + "|" + h(n.getValue(x, y, z)));
            }
        }
    }
}
