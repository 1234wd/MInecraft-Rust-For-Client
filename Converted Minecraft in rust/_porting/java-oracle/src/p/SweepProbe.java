	static boolean collectorThrowsSame(net.minecraft.util.ExceptionCollector<Throwable> collector, Throwable expected) {
		try {
			collector.throwIfPresent();
			return expected == null;
		} catch (Throwable actual) {
			return actual == expected;
		}
	}

