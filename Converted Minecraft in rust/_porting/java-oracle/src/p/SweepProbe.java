	// ---- DSLOT: DataSlot's three factories

	/**
	 * Ops: {@code g} = get(), {@code sV} = set(V), {@code k} = checkAndClearUpdateFlag(),
	 * {@code wI=V} = write V at I of the backing storage behind the slot's back.
	 */
	static String runSlot(net.minecraft.world.inventory.DataSlot slot, java.util.function.BiConsumer<Integer, Integer> backdoor, String script) {
		StringBuilder o = new StringBuilder();
		for (String op : script.split(" ")) {
			String r;
			try {
				if (op.equals("g")) {
					r = i(slot.get());
				} else if (op.equals("k")) {
					r = b(slot.checkAndClearUpdateFlag());
				} else if (op.startsWith("s")) {
					slot.set(Integer.parseInt(op.substring(1)));
					r = "ok";
				} else {
					String[] kv = op.substring(1).split("=");
					backdoor.accept(Integer.parseInt(kv[0]), Integer.parseInt(kv[1]));
					r = "ok";
				}
			} catch (RuntimeException e) {
				r = ex(e);
			}
			if (o.length() > 0) {
				o.append(',');
			}
			o.append(r);
		}
		return o.toString();
	}

