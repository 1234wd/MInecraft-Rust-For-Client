	// ---- SAMPLELOG: LocalSampleLogger (and the AbstractSampleLogger half it inherits)

	/**
	 * Constructor descriptor: {@code 1:D} = new LocalSampleLogger(D); {@code 2:D:a,b,..} =
	 * new LocalSampleLogger(D, new long[]{a, b, ..}) ({@code 2:D:} with an empty array).
	 */
	static net.minecraft.util.debugchart.LocalSampleLogger newLogger(String desc) {
		String[] parts = desc.split(":", -1);
		int dims = Integer.parseInt(parts[1]);
		if (parts[0].equals("1")) {
			return new net.minecraft.util.debugchart.LocalSampleLogger(dims);
		}
		return new net.minecraft.util.debugchart.LocalSampleLogger(dims, longs(parts[2]));
	}

	/** {@code a,b,c} -> long[]; empty string -> long[0]. */
	static long[] longs(String csv) {
		if (csv.isEmpty()) {
			return new long[0];
		}
		String[] p = csv.split(",");
		long[] r = new long[p.length];
		for (int k = 0; k < p.length; k++) {
			r[k] = Long.parseLong(p[k]);
		}
		return r;
	}

	/**
	 * Ops: {@code lV} = logSample(V); {@code pV@D} = logPartialSample(V, D); {@code f<csv>} =
	 * logFullSample(longs(csv)) ({@code f} alone: an empty array); {@code nK@B} = logSample(B),
	 * logSample(B+1), .. K times; {@code gI} = get(I); {@code gI@D} = get(I, D); {@code z} = size();
	 * {@code c} = capacity(); {@code r} = reset(); {@code a} = every held sample, every dimension.
	 */
	static String runLogger(net.minecraft.util.debugchart.LocalSampleLogger lg, int dims, String script) {
		StringBuilder o = new StringBuilder();
		for (String op : script.split(" ")) {
			String r;
			try {
				char k = op.charAt(0);
				String arg = op.substring(1);
				if (k == 'l') {
					lg.logSample(Long.parseLong(arg));
					r = "ok";
				} else if (k == 'p') {
					String[] vd = arg.split("@");
					lg.logPartialSample(Long.parseLong(vd[0]), Integer.parseInt(vd[1]));
					r = "ok";
				} else if (k == 'f') {
					lg.logFullSample(longs(arg));
					r = "ok";
				} else if (k == 'n') {
					String[] kb = arg.split("@");
					long base = Long.parseLong(kb[1]);
					for (int q = 0; q < Integer.parseInt(kb[0]); q++) {
						lg.logSample(base + q);
					}
					r = "ok";
				} else if (k == 'g') {
					if (arg.contains("@")) {
						String[] id = arg.split("@");
						r = l(lg.get(Integer.parseInt(id[0]), Integer.parseInt(id[1])));
					} else {
						r = l(lg.get(Integer.parseInt(arg)));
					}
				} else if (k == 'z') {
					r = i(lg.size());
				} else if (k == 'c') {
					r = i(lg.capacity());
				} else if (k == 'r') {
					lg.reset();
					r = "ok";
				} else {
					StringBuilder all = new StringBuilder();
					for (int s = 0; s < lg.size(); s++) {
						if (s > 0) {
							all.append(';');
						}
						for (int d = 0; d < dims; d++) {
							if (d > 0) {
								all.append('/');
							}
							all.append(lg.get(s, d));
						}
					}
					r = "[" + all + "]";
				}
			} catch (RuntimeException e) {
				r = ex(e);
			}
			if (o.length() > 0) {
				o.append(',');
			}
			o.append(r);
		}
		return o.toString();
	}

