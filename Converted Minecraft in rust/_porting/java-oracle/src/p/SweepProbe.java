	// ---- FFLAG / FFSET / FFSETOP: FeatureFlag and FeatureFlagSet

	static net.minecraft.world.flag.FeatureFlag newFlag(net.minecraft.world.flag.FeatureFlagUniverse u, int bit) throws Exception {
		java.lang.reflect.Constructor<net.minecraft.world.flag.FeatureFlag> c = net.minecraft.world.flag.FeatureFlag.class
			.getDeclaredConstructor(net.minecraft.world.flag.FeatureFlagUniverse.class, int.class);
		c.setAccessible(true);
		return c.newInstance(u, bit);
	}

	/** Universes: A and B are BOTH named "main" (different objects); C is "other". */
	static net.minecraft.world.flag.FeatureFlagUniverse UA, UB, UC;
	/** Flag pool, by name: universe letter + bit. */
	static final String[] FLAG_NAMES = {"A0", "A1", "A5", "A63", "B0", "B1", "C3"};
	static java.util.Map<String, net.minecraft.world.flag.FeatureFlag> FLAGS = new java.util.LinkedHashMap<>();

	static String universeLabel(Object u) {
		if (u == null) {
			return "null";
		}
		return u == UA ? "A" : u == UB ? "B" : u == UC ? "C" : "?";
	}

	/**
	 * A set descriptor: {@code E} = of(); {@code 1:X} = of(X); {@code N:X,Y,...} = of(X, Y...)
	 * ({@code N:X} is the varargs overload with no extra flags); {@code C:U:X,Y} =
	 * create(universe U, [X, Y]) in that order ({@code C:U:} with no flags).
	 */
	static net.minecraft.world.flag.FeatureFlagSet build(String desc) throws Exception {
		if (desc.equals("E")) {
			return net.minecraft.world.flag.FeatureFlagSet.of();
		}
		if (desc.startsWith("1:")) {
			return net.minecraft.world.flag.FeatureFlagSet.of(FLAGS.get(desc.substring(2)));
		}
		if (desc.startsWith("N:")) {
			String[] names = desc.substring(2).split(",");
			net.minecraft.world.flag.FeatureFlag[] rest = new net.minecraft.world.flag.FeatureFlag[names.length - 1];
			for (int k = 1; k < names.length; k++) {
				rest[k - 1] = FLAGS.get(names[k]);
			}
			return net.minecraft.world.flag.FeatureFlagSet.of(FLAGS.get(names[0]), rest);
		}
		// C:U:...
		String[] parts = desc.split(":", -1);
		net.minecraft.world.flag.FeatureFlagUniverse u = parts[1].equals("A") ? UA : parts[1].equals("B") ? UB : UC;
		java.util.List<net.minecraft.world.flag.FeatureFlag> list = new java.util.ArrayList<>();
		if (!parts[2].isEmpty()) {
			for (String n : parts[2].split(",")) {
				list.add(FLAGS.get(n));
			}
		}
		java.lang.reflect.Method create = net.minecraft.world.flag.FeatureFlagSet.class
			.getDeclaredMethod("create", net.minecraft.world.flag.FeatureFlagUniverse.class, java.util.Collection.class);
		create.setAccessible(true);
		try {
			return (net.minecraft.world.flag.FeatureFlagSet) create.invoke(null, u, list);
		} catch (java.lang.reflect.InvocationTargetException e) {
			throw (Exception) e.getCause();
		}
	}

	/** {@code universe|mask|hashCode|toString|isEmpty|contains-bitstring over FLAG_NAMES}. */
	static String state(net.minecraft.world.flag.FeatureFlagSet s) throws Exception {
		StringBuilder c = new StringBuilder();
		for (String n : FLAG_NAMES) {
			c.append(s.contains(FLAGS.get(n)) ? '1' : '0');
		}
		return universeLabel(field(s, "universe")) + "|" + field(s, "mask") + "|" + s.hashCode() + "|" + esc(s.toString())
			+ "|" + (s.isEmpty() ? '1' : '0') + "|" + c;
	}

	static void featureFlags() throws Exception {
		// HCMIX: fastutil's HashCommon.mix(long), all 64 bits (FeatureFlagSet only keeps the low 32)
		long[] mixIn = {0L, 1L, -1L, 2L, 0x80000000L, 0xffffffffL, 0x100000000L, Long.MIN_VALUE, Long.MAX_VALUE,
			0x123456789abcdefL, -7046029254386353131L, 15L, 1L << 63 | 1L, 0xdeadbeefcafebabeL};
		for (long x : mixIn) {
			row("HCMIX", l(x), l(it.unimi.dsi.fastutil.HashCommon.mix(x)));
		}

		net.minecraft.world.flag.FeatureFlagUniverse u = new net.minecraft.world.flag.FeatureFlagUniverse("main");
		for (int bit : new int[]{0, 1, 5, 31, 32, 62, 63, 64, 65, 127, -1, -63, -64, MIN, MAX}) {
			net.minecraft.world.flag.FeatureFlag fl = newFlag(u, bit);
			row("FFLAG", i(bit), String.valueOf(field(fl, "mask")), b(field(fl, "universe") == u));
		}

		UA = new net.minecraft.world.flag.FeatureFlagUniverse("main");
		UB = new net.minecraft.world.flag.FeatureFlagUniverse("main");
		UC = new net.minecraft.world.flag.FeatureFlagUniverse("other");
		for (String n : FLAG_NAMES) {
			net.minecraft.world.flag.FeatureFlagUniverse u2 = n.charAt(0) == 'A' ? UA : n.charAt(0) == 'B' ? UB : UC;
			FLAGS.put(n, newFlag(u2, Integer.parseInt(n.substring(1))));
		}

		String[] descs = {
			"E", "1:A0", "1:A63", "1:B0", "1:C3", "N:A0", "N:A0,A1", "N:A1,A0,A5", "N:A63,A0", "N:A0,A0",
			"N:B0,B1", "N:A0,B0", "N:A0,A1,C3", "N:C3,A0", "C:A:", "C:A:A0", "C:A:A0,A1,A5,A63", "C:B:B1",
			"C:A:B0", "C:A:A0,B1", "C:C:C3", "C:B:", "C:C:A0,C3"
		};
		java.util.List<String> valid = new java.util.ArrayList<>();
		for (String desc : descs) {
			String r;
			try {
				r = state(build(desc));
				valid.add(desc);
			} catch (RuntimeException e) {
				r = ex(e);
			}
			row("FFSET", desc, r);
		}

		// Every ordered pair of buildable sets.
		for (String x : valid) {
			for (String y : valid) {
				net.minecraft.world.flag.FeatureFlagSet sx = build(x);
				net.minecraft.world.flag.FeatureFlagSet sy = build(y);
				String join;
				try {
					join = state(sx.join(sy));
				} catch (RuntimeException e) {
					join = ex(e);
				}
				String sub;
				try {
					sub = state(sx.subtract(sy));
				} catch (RuntimeException e) {
					sub = ex(e);
				}
				row("FFSETOP", x, y, b(sx.isSubsetOf(sy)), b(sx.intersects(sy)), b(sx.equals(sy)), join, sub);
			}
		}
	}

	// ---- FRAME / FRAMEEQ

	static void frame() {
		StringBuilder log = new StringBuilder();
		net.minecraft.commands.CommandResultCallback cbA = (success, result) -> log.append(success ? 'S' : 'F').append(result).append(' ');
		net.minecraft.commands.CommandResultCallback cbB = (success, result) -> log.append('b');
		net.minecraft.commands.execution.Frame.FrameControl fcA = () -> log.append("D ");
		net.minecraft.commands.execution.Frame.FrameControl fcB = () -> log.append('d');

		// Script: Sv = returnSuccess(v), F = returnFailure(), D = discard().
		String script = "S5 F D S-3 S2147483647 D S-2147483648 F S0";
		for (int depth : new int[]{0, 1, -1, MIN, MAX}) {
			net.minecraft.commands.execution.Frame fr = new net.minecraft.commands.execution.Frame(depth, cbA, fcA);
			log.setLength(0);
			for (String op : script.split(" ")) {
				switch (op.charAt(0)) {
					case 'S' -> fr.returnSuccess(Integer.parseInt(op.substring(1)));
					case 'F' -> fr.returnFailure();
					default -> fr.discard();
				}
			}
			row("FRAME", i(depth), script, esc(log.toString().trim()), i(fr.depth()), b(fr.returnValueConsumer() == cbA),
				b(fr.frameControl() == fcA));
		}

		// EMPTY swallows both results.
		net.minecraft.commands.execution.Frame empty = new net.minecraft.commands.execution.Frame(3,
			net.minecraft.commands.CommandResultCallback.EMPTY, fcA);
		log.setLength(0);
		empty.returnSuccess(9);
		empty.returnFailure();
		empty.discard();
		row("FRAME", "EMPTY", "S9 F D", esc(log.toString().trim()), i(empty.depth()), "false", b(empty.frameControl() == fcA));

		net.minecraft.commands.execution.Frame f1 = new net.minecraft.commands.execution.Frame(1, cbA, fcA);
		row("FRAMEEQ", "self", b(f1.equals(f1)));
		row("FRAMEEQ", "same-components", b(f1.equals(new net.minecraft.commands.execution.Frame(1, cbA, fcA))));
		row("FRAMEEQ", "other-depth", b(f1.equals(new net.minecraft.commands.execution.Frame(2, cbA, fcA))));
		row("FRAMEEQ", "other-callback", b(f1.equals(new net.minecraft.commands.execution.Frame(1, cbB, fcA))));
		row("FRAMEEQ", "other-control", b(f1.equals(new net.minecraft.commands.execution.Frame(1, cbA, fcB))));
		row("FRAMEEQ", "both-other", b(f1.equals(new net.minecraft.commands.execution.Frame(1, cbB, fcB))));
	}

	// ---- SCDATA: SimpleContainerData

	/** Ops: {@code gN} = get(N), {@code sN=V} = set(N, V), {@code c} = getCount(). */
	static String runContainer(net.minecraft.world.inventory.ContainerData data, String script) {
		StringBuilder o = new StringBuilder();
		for (String op : script.split(" ")) {
			String r;
			try {
				if (op.equals("c")) {
					r = i(data.getCount());
				} else if (op.startsWith("g")) {
					r = i(data.get(Integer.parseInt(op.substring(1))));
				} else {
					String[] kv = op.substring(1).split("=");
					data.set(Integer.parseInt(kv[0]), Integer.parseInt(kv[1]));
					r = "ok";
				}
			} catch (RuntimeException e) {
				r = ex(e);
			}
			if (o.length() > 0) {
				o.append(',');
			}
			o.append(r);
		}
		return o.toString();
	}

