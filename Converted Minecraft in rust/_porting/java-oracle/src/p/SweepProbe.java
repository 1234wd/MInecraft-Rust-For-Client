	/**
	 * Builder script ops: {@code sNAME} withSampler; {@code uNAME:TYPE} withUniform(name, type);
	 * {@code tNAME:TYPE:FORMAT} withUniform(name, type, format); {@code b} build (the layout is kept).
	 */
	static String runBuilder(String script, java.util.List<com.mojang.blaze3d.pipeline.BindGroupLayout> built) {
		com.mojang.blaze3d.pipeline.BindGroupLayout.Builder bld = com.mojang.blaze3d.pipeline.BindGroupLayout.builder();
		StringBuilder o = new StringBuilder();
		for (String op : script.split(" ")) {
			String r;
			try {
				String[] p = op.substring(1).split(":");
				switch (op.charAt(0)) {
					case 's' -> bld.withSampler(p[0]);
					case 'u' -> bld.withUniform(p[0], com.mojang.blaze3d.shaders.UniformType.valueOf(p[1]));
					case 't' -> bld.withUniform(p[0], com.mojang.blaze3d.shaders.UniformType.valueOf(p[1]), com.mojang.blaze3d.GpuFormat.valueOf(p[2]));
					default -> {
						com.mojang.blaze3d.pipeline.BindGroupLayout l = bld.build();
						built.add(l);
					}
				}
				if (op.charAt(0) == 'b') {
					com.mojang.blaze3d.pipeline.BindGroupLayout l = built.get(built.size() - 1);
					r = "[" + esc(String.join("|", l.getSamplers())) + "/" + esc(l.getUniforms().toString()) + "]";
				} else {
					r = "ok";
				}
			} catch (RuntimeException e) {
				r = ex(e);
			}
			o.append(o.length() > 0 ? "," : "").append(r);
		}
		return o.toString();
	}

