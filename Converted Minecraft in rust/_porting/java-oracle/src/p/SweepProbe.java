	static String vis(int mod) {
		return java.lang.reflect.Modifier.isPublic(mod) ? "public" : java.lang.reflect.Modifier.isProtected(mod) ? "protected"
			: java.lang.reflect.Modifier.isPrivate(mod) ? "private" : "package";
	}

	/**
	 * {@code API24 class kind signature modifiers}, sorted per class: kind = ctor | method | field;
	 * modifiers = visibility + static/abstract/default/final as they apply. Synthetic and bridge
	 * members are skipped, as are the members of anonymous classes (they belong to the factory).
	 */
	static void apiShapes() throws Exception {
		apiShapes(API_CLASSES, "API24", "API24SUP");
		apiShapes(API25_CLASSES, "S25_API", "S25_SUP");
		apiShapes(API26_CLASSES, "S26_API", "S26_SUP");
	}

	static void apiShapes(String[] classes, String memberGroup, String superGroup) throws Exception {
		for (String cn : classes) {
			Class<?> c = Class.forName(cn);
			String simple = cn.substring(cn.lastIndexOf('.') + 1);
			java.util.List<String> rs = new java.util.ArrayList<>();
			for (java.lang.reflect.Constructor<?> k : c.getDeclaredConstructors()) {
				if (k.isSynthetic()) {
					continue;
				}
				StringBuilder s = new StringBuilder("<init>(");
				java.lang.reflect.Type[] ps = k.getGenericParameterTypes();
				for (int q = 0; q < ps.length; q++) {
					s.append(q == 0 ? "" : ",").append(ps[q].getTypeName());
				}
				s.append(')');
				rs.add("ctor\t" + s + "\t" + vis(k.getModifiers()) + (k.isVarArgs() ? " varargs" : ""));
			}
			for (java.lang.reflect.Method m : c.getDeclaredMethods()) {
				if (m.isSynthetic() || m.isBridge()) {
					continue;
				}
				StringBuilder s = new StringBuilder(m.getName()).append('(');
				java.lang.reflect.Type[] ps = m.getGenericParameterTypes();
				for (int q = 0; q < ps.length; q++) {
					s.append(q == 0 ? "" : ",").append(ps[q].getTypeName());
				}
				s.append(')').append(m.getGenericReturnType().getTypeName());
				int mod = m.getModifiers();
				String kind = java.lang.reflect.Modifier.isStatic(mod) ? " static"
					: java.lang.reflect.Modifier.isAbstract(mod) ? " abstract" : m.isDefault() ? " default" : "";
				rs.add("method\t" + s + "\t" + vis(mod) + kind);
			}
			for (java.lang.reflect.Field fl : c.getDeclaredFields()) {
				if (fl.isSynthetic()) {
					continue;
				}
				int mod = fl.getModifiers();
				rs.add("field\t" + fl.getName() + ":" + fl.getGenericType().getTypeName() + "\t" + vis(mod)
					+ (java.lang.reflect.Modifier.isStatic(mod) ? " static" : "") + (java.lang.reflect.Modifier.isFinal(mod) ? " final" : ""));
			}
			java.util.Collections.sort(rs);
			for (String s : rs) {
				row(memberGroup, simple, s);
			}
			StringBuilder sup = new StringBuilder();
			for (java.lang.reflect.Type t : c.getGenericInterfaces()) {
				sup.append(sup.length() == 0 ? "" : ",").append(t.getTypeName());
			}
			if (c.getSuperclass() != null && c.getSuperclass() != Object.class) {
				sup.append(sup.length() == 0 ? "" : ",").append("extends ").append(c.getGenericSuperclass().getTypeName());
			}
			String kind = c.isAnnotation() ? "annotation" : c.isInterface() ? "interface" : c.isRecord() ? "record" : c.isEnum() ? "enum"
				: java.lang.reflect.Modifier.isAbstract(c.getModifiers()) ? "abstract class" : "class";
			row(superGroup, simple, sup.length() == 0 ? "-" : sup.toString(), kind);
		}
	}
