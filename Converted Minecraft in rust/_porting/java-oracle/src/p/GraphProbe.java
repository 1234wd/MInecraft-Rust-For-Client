/**
 * Session 19 probe for DynamicGraphMinFixedPoint / LeveledPriorityQueue (through concrete
 * ChunkTracker and SectionTracker subclasses), ChunkTrackingView, and RegionBitmap. Run against
 * the real 26.2 jar (JDK 25); output committed as _porting/test-data/graph_probe.txt.
 *
 * The Rust twin in _porting/tests/session19_consts.rs runs the SAME scripts below; any change
 * here must be mirrored there.
 */
public class GraphProbe {
    static PrintStream out;

    /** A minimal concrete ChunkTracker: levels and source levels in maps, default levelCount-1. */
    static class CT extends ChunkTracker {
        final Long2IntOpenHashMap levels = new Long2IntOpenHashMap();
        final Long2IntOpenHashMap sources = new Long2IntOpenHashMap();

        CT(int levelCount) {
            super(levelCount, 16, 256);
            levels.defaultReturnValue(levelCount - 1);
            sources.defaultReturnValue(levelCount - 1);
        }

        @Override
        protected int getLevelFromSource(long to) {
            return sources.get(to);
        }

        @Override
        protected int getLevel(long node) {
            return levels.get(node);
        }

        @Override
        protected void setLevel(long node, int level) {
            if (level >= this.levelCount - 1) {
                levels.remove(node);
            } else {
                levels.put(node, level);
            }
        }

        int run(int n) {
            return runUpdates(n);
        }

        String snapshot() {
            TreeMap<String, Integer> sorted = new TreeMap<>();
            for (long k : levels.keySet()) {
                sorted.put(String.format("%+06d,%+06d", ChunkPos.getX(k), ChunkPos.getZ(k)), levels.get(k));
            }
            StringBuilder sb = new StringBuilder();
            sorted.forEach((k, v) -> sb.append(k).append('=').append(v).append(';'));
            return sb.toString();
        }
    }

    static class ST extends SectionTracker {
        final Long2IntOpenHashMap levels = new Long2IntOpenHashMap();
        final Long2IntOpenHashMap sources = new Long2IntOpenHashMap();

        ST(int levelCount) {
            super(levelCount, 16, 256);
            levels.defaultReturnValue(levelCount - 1);
            sources.defaultReturnValue(levelCount - 1);
        }

        @Override
        protected int getLevelFromSource(long to) {
            return sources.get(to);
        }

        @Override
        protected int getLevel(long node) {
            return levels.get(node);
        }

        @Override
        protected void setLevel(long node, int level) {
            if (level >= this.levelCount - 1) {
                levels.remove(node);
            } else {
                levels.put(node, level);
            }
        }

        int run(int n) {
            return runUpdates(n);
        }

        String snapshot() {
            TreeMap<String, Integer> sorted = new TreeMap<>();
            for (long k : levels.keySet()) {
                sorted.put(String.format("%+06d,%+06d,%+06d", SectionPos.x(k), SectionPos.y(k), SectionPos.z(k)), levels.get(k));
            }
            StringBuilder sb = new StringBuilder();
            sorted.forEach((k, v) -> sb.append(k).append('=').append(v).append(';'));
            return sb.toString();
        }
    }

    static void chunk(String step, CT t, int returned) {
        out.println("graph.chunk|" + step + "|" + returned + "|" + t.getQueueSize() + "|" + t.snapshot());
    }

    static void section(String step, ST t, int returned) {
        out.println("graph.section|" + step + "|" + returned + "|" + t.getQueueSize() + "|" + t.snapshot());
    }

    public static void main(String[] args) throws Exception {
        out = new PrintStream(new java.io.FileOutputStream(args[0]), true, StandardCharsets.UTF_8);
        out.println("# graph probe -- GENERATED by _porting/java-oracle/src/p/GraphProbe.java against minecraft-merged-deobf-26.2.jar");

        // ---------------- ChunkTracker script (levelCount 12)
        CT c = new CT(12);
        long a = ChunkPos.pack(0, 0), b = ChunkPos.pack(4, 1), d = ChunkPos.pack(-3, -2);
        c.sources.put(a, 3);
        c.update(a, 3, true);
        c.sources.put(b, 5);
        c.update(b, 5, true);
        chunk("s1.enqueued", c, -1);
        chunk("s2.run7", c, c.run(7));
        chunk("s3.run13", c, c.run(13));
        chunk("s4.runAll", c, c.run(100000));
        c.sources.remove(a);
        c.update(a, 11, false);
        chunk("s5.raised", c, -1);
        chunk("s6.run5", c, c.run(5));
        chunk("s7.run17", c, c.run(17));
        chunk("s8.runAll", c, c.run(100000));
        c.sources.put(d, 0);
        c.update(d, 0, true);
        chunk("s9.run3", c, c.run(3));
        c.removeIf(node -> ChunkPos.getX(node) < -4);
        chunk("s10.removeIf", c, -1);
        chunk("s11.runAll", c, c.run(100000));
        c.sources.put(b, 9);
        c.update(b, 9, false);
        chunk("s12.run11", c, c.run(11));
        chunk("s13.runAll", c, c.run(100000));
        c.sources.put(a, 7);
        c.update(a, 7, true);
        c.sources.put(ChunkPos.pack(2, 0), 2);
        c.update(ChunkPos.pack(2, 0), 2, true);
        chunk("s14.run9", c, c.run(9));
        chunk("s15.runAll", c, c.run(100000));

        // ---------------- SectionTracker script (levelCount 6)
        ST s = new ST(6);
        long p = SectionPos.asLong(0, 0, 0), q = SectionPos.asLong(3, -1, 2), r = SectionPos.asLong(-2, 4, -1);
        s.sources.put(p, 1);
        s.update(p, 1, true);
        s.sources.put(q, 2);
        s.update(q, 2, true);
        section("t1.run10", s, s.run(10));
        section("t2.run31", s, s.run(31));
        section("t3.runAll", s, s.run(100000));
        s.sources.remove(p);
        s.update(p, 5, false);
        section("t4.run20", s, s.run(20));
        section("t5.runAll", s, s.run(100000));
        s.sources.put(r, 0);
        s.update(r, 0, true);
        section("t6.run7", s, s.run(7));
        s.removeIf(node -> SectionPos.y(node) > 4);
        section("t7.removeIf", s, -1);
        section("t8.runAll", s, s.run(100000));

        // ---------------- ChunkTrackingView
        int[][] views = {{0, 0, 2}, {1, 0, 2}, {0, 3, 3}, {10, 10, 1}, {0, 0, 0}, {-5, 7, 4}};
        for (int[] v : views) {
            ChunkTrackingView view = ChunkTrackingView.of(new ChunkPos(v[0], v[1]), v[2]);
            StringBuilder sb = new StringBuilder();
            view.forEach(pos -> sb.append(pos.x()).append(',').append(pos.z()).append(';'));
            out.println("view.forEach|" + v[0] + "," + v[1] + "," + v[2] + "|" + sb);
            for (int x = v[0] - v[2] - 3; x <= v[0] + v[2] + 3; x++) {
                for (int z = v[1] - v[2] - 3; z <= v[1] + v[2] + 3; z++) {
                    out.println("view.contains|" + v[0] + "," + v[1] + "," + v[2] + "|" + x + "," + z + "|"
                        + view.contains(x, z, true) + "|" + view.contains(x, z, false) + "|" + view.isInViewDistance(x, z));
                }
            }
        }
        List<ChunkTrackingView> all = new ArrayList<>();
        all.add(ChunkTrackingView.EMPTY);
        for (int[] v : views) {
            all.add(ChunkTrackingView.of(new ChunkPos(v[0], v[1]), v[2]));
        }
        for (int i = 0; i < all.size(); i++) {
            for (int j = 0; j < all.size(); j++) {
                StringBuilder enter = new StringBuilder(), leave = new StringBuilder();
                ChunkTrackingView.difference(all.get(i), all.get(j),
                    pos -> enter.append(pos.x()).append(',').append(pos.z()).append(';'),
                    pos -> leave.append(pos.x()).append(',').append(pos.z()).append(';'));
                out.println("view.difference|" + i + "|" + j + "|" + enter + "|" + leave);
            }
        }

        // ---------------- RegionBitmap
        RegionBitmap bm = new RegionBitmap();
        bm.force(0, 2);
        out.println("bitmap|force0,2|-|" + bm.getUsed());
        out.println("bitmap|alloc1|" + bm.allocate(1) + "|" + bm.getUsed());
        out.println("bitmap|alloc3|" + bm.allocate(3) + "|" + bm.getUsed());
        bm.free(2, 1);
        out.println("bitmap|free2,1|-|" + bm.getUsed());
        out.println("bitmap|alloc2|" + bm.allocate(2) + "|" + bm.getUsed());
        out.println("bitmap|alloc1|" + bm.allocate(1) + "|" + bm.getUsed());
        bm.free(3, 3);
        out.println("bitmap|free3,3|-|" + bm.getUsed());
        out.println("bitmap|alloc2|" + bm.allocate(2) + "|" + bm.getUsed());
        out.println("bitmap|alloc0|" + bm.allocate(0) + "|" + bm.getUsed());
        try {
            bm.force(5, -1);
            out.println("bitmap|force5,-1|ok|" + bm.getUsed());
        } catch (Exception e) {
            out.println("bitmap|force5,-1|" + e.getClass().getName() + ": " + e.getMessage() + "|" + bm.getUsed());
        }
        out.close();
    }
}
